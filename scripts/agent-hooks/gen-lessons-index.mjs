// Rebuilds docs/solutions/INDEX.md and .cursor/rules/compound-lessons.mdc from
// the YAML frontmatter of every solution doc. Invoked by gen-lessons-index.sh.
// No external dependencies — a minimal frontmatter parser covers the small,
// well-formed subset that /ce-compound writes (scalars, flow arrays, block lists).

import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'

const repoRoot = process.argv[2] || process.cwd()
const solutionsDir = join(repoRoot, 'docs', 'solutions')
const indexPath = join(solutionsDir, 'INDEX.md')
const mdcPath = join(repoRoot, '.cursor', 'rules', 'compound-lessons.mdc')

function stripQuotes(s) {
  return s.replace(/^['"]|['"]$/g, '').trim()
}

// Parse the leading --- ... --- frontmatter block into { key: value | string[] }.
function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!m) return {}
  const lines = m[1].split(/\r?\n/)
  const out = {}
  let listKey = null
  for (const fmLine of lines) {
    const blockItem = fmLine.match(/^\s+-\s+(.*)$/)
    if (listKey && blockItem) {
      out[listKey].push(stripQuotes(blockItem[1]))
      continue
    }
    const kv = fmLine.match(/^([A-Za-z0-9_]+):\s*(.*)$/)
    if (!kv) continue
    const [, key, rawValue] = kv
    const value = rawValue.trim()
    if (value === '') {
      // A block list (its `  - item` lines follow) — start collecting.
      listKey = key
      out[key] = []
    } else if (value.startsWith('[') && value.endsWith(']')) {
      listKey = null
      out[key] = value
        .slice(1, -1)
        .split(',')
        .map((s) => stripQuotes(s))
        .filter(Boolean)
    } else {
      listKey = null
      out[key] = stripQuotes(value)
    }
  }
  return out
}

function asArray(v) {
  if (Array.isArray(v)) return v
  if (typeof v === 'string' && v) return [v]
  return []
}

const entries = []
if (existsSync(solutionsDir)) {
  const files = readdirSync(solutionsDir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md' && f !== 'INDEX.md')
    .toSorted()
  for (const file of files) {
    const fm = parseFrontmatter(readFileSync(join(solutionsDir, file), 'utf8'))
    if (!fm.title) continue
    const tags = asArray(fm.tags)
    const symptom = asArray(fm.symptoms)[0] || ''
    entries.push({ file, title: fm.title, date: fm.date || '', tags, symptom })
  }
}

function line(e) {
  const parts = [`**${e.title}**`]
  if (e.date) parts.push(e.date)
  if (e.tags.length) parts.push(e.tags.join(', '))
  if (e.symptom) parts.push(e.symptom)
  return `- ${parts.join(' · ')} — [${e.file}](./${e.file})`
}

const body = entries.length
  ? entries.map(line).join('\n')
  : '_No solutions captured yet. Run `/ce-compound` after solving a non-obvious problem._'

const indexContent = `<!-- GENERATED by scripts/agent-hooks/gen-lessons-index.sh — do not edit by hand. -->

# Solutions index

Prior solved problems. Search here before debugging. Full write-ups live in the
linked files; see [README.md](./README.md) for the format and when to add one.

${body}
`

const mdcContent = `---
description: Prior solved problems captured in docs/solutions — search here before debugging
alwaysApply: true
---

<!-- GENERATED by scripts/agent-hooks/gen-lessons-index.sh — do not edit by hand. -->

# Compound engineering: prior solutions

Before debugging or making a decision, check whether it was already solved. Each
line links to a full write-up under \`docs/solutions/\`.

${body}
`

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return false
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  return true
}

const a = writeIfChanged(indexPath, indexContent)
const b = writeIfChanged(mdcPath, mdcContent)
if (a || b) console.error(`gen-lessons-index: ${entries.length} solution(s) indexed`)
